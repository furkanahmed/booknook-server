export async function seedBooks() {
  try {
    const db = await getDb();
    const booksCol = db.collection("books");

    const count = await booksCol.countDocuments({ title: { $exists: true } });
    if (count === 0) {
      console.log("Seeding initial 12 authentic books into MongoDB...");
      await booksCol.insertMany(initialBooks);
      console.log("Successfully seeded 12 books!");
    } else {
      console.log(`MongoDB already has ${count} books. Skipping initial seed.`);
    }
  } catch (err) {
    console.error("Seeding error:", err.message);
  }
}
